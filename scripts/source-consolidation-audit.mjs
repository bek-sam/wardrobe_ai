import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import prettier from "prettier";

const root = process.cwd();
const sourceRoots = ["src", "backend/src", "worker/src", "ai-orchestration/src", "contracts/src"];
const reportPath = path.join(root, "docs/source-consolidation-audit.md");

function walk(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(target) : [target];
  });
}

function relative(file) {
  return path.relative(root, file).split(path.sep).join("/");
}

function lines(file) {
  const source = fs.readFileSync(file, "utf8");
  return source.length === 0 ? 0 : source.split(/\r?\n/).length - (source.endsWith("\n") ? 1 : 0);
}

function reason(file) {
  if (/(?:^|\/)app\/(?:.*\/)?(?:layout|page|route)\.tsx?$/.test(file) || file === "src/proxy.ts") {
    return "Framework entry";
  }
  if (file.startsWith("contracts/src/")) return "Network contract";
  if (/(?:^|\/)(?:server|main|app|dispatcher)\.ts$/.test(file)) return "Process entry";
  if (/\/(?:schemas?|types?|contracts?|constants|events)(?:\/index)?\.ts$/.test(file)) return "Domain contract";
  if (/\/lib\/(?:backend|supabase|ai\/client|env)\//.test(file)) return "Runtime adapter";
  if (file.startsWith("worker/src/jobs/")) return "Durable workflow seam";
  if (file.includes("/auth/") || file.includes("/security/")) return "Security boundary";
  if (file.startsWith("src/features/") || file.startsWith("src/components/")) return "Presentation owner";
  if (path.basename(file).startsWith("index.")) return "Public module surface";
  return "Cohesive implementation";
}

const files = sourceRoots
  .flatMap((sourceRoot) => walk(path.join(root, sourceRoot)))
  .filter((file) => [".ts", ".tsx"].includes(path.extname(file)))
  .map((file) => ({ file: relative(file), lines: lines(file) }))
  .sort((a, b) => a.file.localeCompare(b.file));
const short = files.filter((file) => file.lines < 50).map((file) => ({ ...file, reason: reason(file.file) }));

function markdown() {
  const totals = sourceRoots.map((sourceRoot) => {
    const members = files.filter((file) => file.file.startsWith(`${sourceRoot}/`));
    return {
      sourceRoot,
      files: members.length,
      lines: members.reduce((sum, file) => sum + file.lines, 0),
      short: members.filter((file) => file.lines < 50).length,
    };
  });
  return `# Source consolidation audit

Status: generated by \`scripts/source-consolidation-audit.mjs\`.

File length is an observation, not an architectural rule. The former 50-line hook is removed. Files are combined when they have one owner and split only for framework identity, a network/security/runtime contract, a durable retry seam, or a genuinely reusable module. This avoids both tiny-file sprawl and unsafe “one giant file” coupling.

## Active source

| Owner | Modules | Lines | Below 50 lines |
| --- | ---: | ---: | ---: |
${totals.map((item) => `| \`${item.sourceRoot}/\` | ${item.files} | ${item.lines.toLocaleString()} | ${item.short} |`).join("\n")}

Root \`src/\` is the Frontend. The old duplicate \`frontend/\` project and all root API/job/provider/database implementations are removed.

## Short-module inventory

Every current file below 50 lines is listed so small modules remain visible during review; the build does not force code to grow or merge merely to cross an arbitrary threshold.

| Lines | Owner reason | File |
| ---: | --- | --- |
${short.map((item) => `| ${item.lines} | ${item.reason} | \`${item.file}\` |`).join("\n")}

## Enforcement

- \`npm run check:architecture\` rejects cross-project implementation imports and forbidden SDK dependencies.
- Frontend cannot contain \`src/app/api\` or \`src/jobs\`, or depend on Supabase, OpenAI, Sharp, Fastify, Backend, Worker, or AI implementations.
- Backend and Worker cannot import the OpenAI SDK; AI Orchestration cannot import database clients.
- A new short file is allowed only when it clarifies ownership. There is deliberately no lines-per-file hook.
`;
}

const prettierOptions = (await prettier.resolveConfig(reportPath)) ?? {};
const expected = await prettier.format(markdown(), { ...prettierOptions, filepath: reportPath });
if (process.argv.includes("--write")) {
  fs.writeFileSync(reportPath, expected);
  console.log(`Wrote ${relative(reportPath)} for ${files.length} active modules.`);
} else if (process.argv.includes("--check")) {
  const current = fs.existsSync(reportPath) ? fs.readFileSync(reportPath, "utf8") : "";
  if (current !== expected) {
    console.error("Source consolidation report is stale. Run npm run audit:consolidation.");
    process.exit(1);
  }
  console.log(`Source consolidation audit passed: ${files.length} active modules inventoried.`);
} else {
  process.stdout.write(expected);
}
